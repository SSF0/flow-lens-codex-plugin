import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {Client} from '@modelcontextprotocol/sdk/client/index.js';
import {StdioClientTransport} from '@modelcontextprotocol/sdk/client/stdio.js';
test('packaged MCP creates a flow, serves panel, and retrieves edits across clients',async t=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'flow-lens-mcp-'));
  const client=new Client({name:'integration-test',version:'1.0.0'});
  t.after(async()=>{await client.close();try{process.kill(JSON.parse(fs.readFileSync(path.join(dir,'endpoint.json'))).pid);}catch{}fs.rmSync(dir,{recursive:true,force:true});});
  await client.connect(new StdioClientTransport({command:process.execPath,args:[path.resolve('dist/mcp.mjs')],env:{...process.env,FLOW_LENS_DATA:dir}}));
  assert.equal((await client.listTools()).tools.length,10);
  const sessionArgs={workspace:dir,threadId:'live-session',title:'Session canvas'};
  const session=JSON.parse((await client.callTool({name:'open_session',arguments:sessionArgs})).content[0].text);
  assert.equal(new URL(session.url).searchParams.get('surface'),'codex');
  const synced=await client.callTool({name:'sync_flow',arguments:{id:session.id,revision:session.revision,nodes:[{id:'method',position:{x:0,y:0},data:{label:'Method',kind:'action'}}],edges:[],summary:'Inspected method'}});
  assert.ok(!synced.isError,JSON.stringify(synced));
  const reopened=JSON.parse((await client.callTool({name:'open_session',arguments:sessionArgs})).content[0].text);
  assert.equal(reopened.id,session.id);assert.equal(reopened.baseline.nodes[0].id,'method');
  const graph={nodes:[{id:'start',position:{x:0,y:0},data:{label:'Start',kind:'start'}}],edges:[]};
  const result=await client.callTool({name:'create_flow',arguments:{id:'integration',threadId:'test-session',workspace:dir,title:'Integration',graph}});
  assert.ok(!result.isError,JSON.stringify(result));const r=JSON.parse(result.content[0].text),url=new URL(r.url);
  assert.equal(url.searchParams.get('surface'),'codex');
  assert.match(await (await fetch(url.origin)).text(),/Flow Lens/);
  assert.equal((await fetch(url.origin+'/api/flows')).status,401);
  assert.equal((await fetch(url.origin+'/health',{headers:{Origin:'https://unrelated.test'}})).status,403);
  const modeResult=await client.callTool({name:'set_flow_mode',arguments:{id:r.id,mode:'edit'}});
  assert.ok(!modeResult.isError);assert.equal(JSON.parse(modeResult.content[0].text).mode,'edit');
  assert.equal(JSON.parse(modeResult.content[0].text).revision,r.revision);
  graph.nodes[0].data.label='Changed';
  const token=new URLSearchParams(url.hash.slice(1)).get('token');
  const threadRead=await fetch(url.origin+'/api/flows/by-thread?thread=live-session',{headers:{Authorization:`Bearer ${token}`}});
  assert.equal((await threadRead.json()).id,session.id);
  const emptyThread=await fetch(url.origin+'/api/flows/by-thread?thread=never-created',{headers:{Authorization:`Bearer ${token}`}});
  assert.equal(await emptyThread.json(),null);
  const saved=await fetch(url.origin+'/api/flows/integration/draft',{method:'POST',headers:{Authorization:`Bearer ${token}`,'Content-Type':'application/json'},body:JSON.stringify({revision:1,graph})});
  assert.equal(saved.status,200);
  const read=JSON.parse((await client.callTool({name:'read_flow',arguments:{id:'integration'}})).content[0].text);
  assert.equal(read.draft.nodes[0].data.label,'Changed');assert.equal(read.changes.length,1);
  for(const mode of ['view','compare','edit']){
    const switched=JSON.parse((await client.callTool({name:'set_flow_mode',arguments:{id:r.id,mode}})).content[0].text);
    assert.equal(switched.mode,mode);assert.equal(switched.revision,read.revision);
    assert.deepEqual(switched.draft,read.draft);assert.deepEqual(switched.baseline,read.baseline);
  }
  assert.equal((await client.callTool({name:'set_flow_mode',arguments:{id:r.id,mode:'invalid'}})).isError,true);
  const unchanged=JSON.parse((await client.callTool({name:'read_flow',arguments:{id:session.id}})).content[0].text);
  assert.equal(unchanged.mode,'view');
});
